"""Session loading, filtering, parsing, and metadata extraction."""

import json
from pathlib import Path
from datetime import datetime
from typing import Optional

from constants import (
    PROJECTS_DIR,
    INTERNAL_MARKER,
)


# ─── Timestamp Parsing ───────────────────────────────────────────────────────────

def parse_timestamp(ts: str) -> Optional[datetime]:
    if not ts:
        return None
    try:
        ts = ts.rstrip("Z")
        return datetime.fromisoformat(ts + "+00:00")
    except Exception:
        return None


# ─── Session File Parsing ────────────────────────────────────────────────────────

def parse_session_file(path: Path) -> list[dict]:
    """Parse a JSONL session file. Returns list of message entries."""
    messages = []
    try:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                messages.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    except Exception:
        pass
    return messages


# ─── Session Filters ─────────────────────────────────────────────────────────────

def is_agent_session(path: Path) -> bool:
    return path.name.startswith("agent-")


def is_internal_session(messages: list[dict]) -> bool:
    """Filter out sessions generated by this ROI script itself."""
    for msg in messages[:5]:
        content = msg.get("message", {}).get("content", [])
        if isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text":
                    if INTERNAL_MARKER in block.get("text", ""):
                        return True
        elif isinstance(content, str) and INTERNAL_MARKER in content:
            return True
    return False


# ─── Message Helpers ─────────────────────────────────────────────────────────────

def get_human_messages(messages: list[dict]) -> list[dict]:
    """Return only human-typed text messages (not tool results)."""
    result = []
    for msg in messages:
        if msg.get("type") != "user":
            continue
        content = msg.get("message", {}).get("content", [])
        if isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text":
                    if block.get("text", "").strip():
                        result.append(msg)
                        break
        elif isinstance(content, str) and content.strip():
            result.append(msg)
    return result


def extract_first_prompt(messages: list[dict]) -> str:
    human = get_human_messages(messages)
    if not human:
        return ""
    content = human[0].get("message", {}).get("content", [])
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                return block.get("text", "")[:500]
    elif isinstance(content, str):
        return content[:500]
    return ""


# ─── Metadata Extraction ─────────────────────────────────────────────────────────

def extract_metadata(session_id: str, messages: list[dict]) -> dict:
    """Extract per-session metadata from parsed messages."""
    timestamps = []
    input_tokens = 0
    output_tokens = 0
    tool_counts: dict[str, int] = {}
    languages: set[str] = set()
    git_commits = 0
    tool_errors = 0
    files_modified: set[str] = set()

    for msg in messages:
        ts = parse_timestamp(msg.get("timestamp", ""))
        if ts:
            timestamps.append(ts)

        m = msg.get("message", {})
        usage = m.get("usage", {})
        input_tokens += usage.get("input_tokens", 0)
        output_tokens += usage.get("output_tokens", 0)

        content = m.get("content", [])
        if not isinstance(content, list):
            continue

        for block in content:
            if not isinstance(block, dict):
                continue
            btype = block.get("type", "")

            if btype == "tool_use":
                tool_name = block.get("name", "unknown")
                tool_counts[tool_name] = tool_counts.get(tool_name, 0) + 1
                inp = block.get("input", {})

                if tool_name == "Bash" and "git commit" in inp.get("command", ""):
                    git_commits += 1

                if tool_name in ("Edit", "Write", "MultiEdit"):
                    fp = inp.get("file_path", "") or inp.get("path", "")
                    if fp:
                        files_modified.add(fp)
                        ext = Path(fp).suffix.lower()
                        if ext:
                            languages.add(ext.lstrip("."))

            elif btype == "tool_result" and block.get("is_error", False):
                tool_errors += 1

    start_time = min(timestamps).isoformat() if timestamps else ""
    end_time = max(timestamps) if timestamps else None
    start_dt = min(timestamps) if timestamps else None
    duration_minutes = 0.0
    if start_dt and end_time:
        duration_minutes = max((end_time - start_dt).total_seconds() / 60.0, 0.0)

    human_msgs = get_human_messages(messages)

    return {
        "session_id": session_id,
        "start_time": start_time,
        "duration_minutes": round(duration_minutes, 2),
        "user_message_count": len(human_msgs),
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "tool_counts": tool_counts,
        "languages": sorted(languages),
        "git_commits": git_commits,
        "user_interruptions": 0,
        "tool_errors": tool_errors,
        "lines_added": 0,
        "lines_removed": 0,
        "files_modified": len(files_modified),
        "first_prompt": extract_first_prompt(messages),
        "transcript_length": 0,  # filled after transcript is built
    }


# ─── Transcript Building ─────────────────────────────────────────────────────────

def build_transcript(messages: list[dict]) -> str:
    """Build a readable transcript string from session messages."""
    parts = []
    for msg in messages:
        msg_type = msg.get("type", "")
        if msg_type not in ("user", "assistant"):
            continue

        m = msg.get("message", {})
        role = m.get("role", msg_type).upper()
        content = m.get("content", [])

        if isinstance(content, str):
            parts.append(f"[{role}]: {content}")
            continue

        if not isinstance(content, list):
            continue

        for block in content:
            if not isinstance(block, dict):
                continue
            btype = block.get("type", "")

            if btype == "text":
                text = block.get("text", "").strip()
                if text:
                    parts.append(f"[{role}]: {text[:3000]}")

            elif btype == "tool_use":
                name = block.get("name", "tool")
                inp = block.get("input", {})
                cmd = inp.get("command", "") or inp.get("file_path", "") or str(inp)[:200]
                parts.append(f"[TOOL USE: {name}] {cmd[:300]}")

            elif btype == "tool_result":
                result_content = block.get("content", [])
                is_err = block.get("is_error", False)
                label = "TOOL ERROR" if is_err else "TOOL RESULT"
                result_text = ""
                if isinstance(result_content, list):
                    for rc in result_content:
                        if isinstance(rc, dict) and rc.get("type") == "text":
                            result_text = rc.get("text", "")[:500]
                            break
                elif isinstance(result_content, str):
                    result_text = result_content[:500]
                parts.append(f"[{label}]: {result_text}")

    return "\n".join(parts)


# ─── Session Loader ──────────────────────────────────────────────────────────────

def load_sessions(since_date: Optional[datetime] = None) -> list[dict]:
    """Load and filter all eligible sessions from ~/.claude/projects/."""
    if not PROJECTS_DIR.exists():
        return []

    sessions = []
    for project_dir in PROJECTS_DIR.iterdir():
        if not project_dir.is_dir():
            continue
        for session_file in project_dir.glob("*.jsonl"):
            if is_agent_session(session_file):
                continue

            messages = parse_session_file(session_file)
            if not messages:
                continue

            if is_internal_session(messages):
                continue

            human_msgs = get_human_messages(messages)
            if len(human_msgs) < 2:
                continue

            metadata = extract_metadata(session_file.stem, messages)

            if metadata["duration_minutes"] < 1:
                continue

            if since_date:
                start = parse_timestamp(metadata["start_time"])
                if start and start < since_date:
                    continue

            transcript = build_transcript(messages)
            metadata["transcript_length"] = len(transcript)

            sessions.append({
                "session_id": session_file.stem,
                "metadata": metadata,
                "messages": messages,
                "transcript": transcript,
            })

    return sessions
